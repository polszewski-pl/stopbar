// Build without TypeScript or a bundler: Node's own type stripping turns src/*.ts into dist/*.js, and gdp-wired's
// compileJs turns the proven rule in src/kernel.ts into a standalone step function (dist/kernel.gen.js).
// Usage: node scripts/build.ts
import {createHash} from 'node:crypto'
import {mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs'
import {stripTypeScriptTypes} from 'node:module'
import {dirname, join, resolve} from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'src'), DIST = join(ROOT, 'dist')
const sha = (s: string | Buffer) => createHash('sha256').update(s).digest('hex')
const t0 = Date.now()

// Node prints an ExperimentalWarning for stripTypeScriptTypes on some versions: keep the build output clean
process.removeAllListeners('warning')

rmSync(DIST, {recursive: true, force: true})
mkdirSync(DIST, {recursive: true})

// 1. src/**/*.ts -> dist/**/*.js (types erased, positions kept; relative .ts imports become .js)
const files = (readdirSync(SRC, {recursive: true}) as string[]).map((f) => f.replace(/\\/g, '/')).filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts'))
for (const f of files) {
  const code = stripTypeScriptTypes(readFileSync(join(SRC, f), 'utf8'), {mode: 'strip'})
  const js = code.replace(/((?:from\s+|import\s*\(\s*)['"])(\.{1,2}\/[^'"]+?)\.ts(['"])/g, '$1$2.js$3')
  if (/from\s+['"]\.{1,2}\/[^'"]+\.ts['"]|import\(\s*['"]\.{1,2}\/[^'"]+\.ts['"]/.test(js)) throw new Error(`${f}: a .ts import was not rewritten`)
  mkdirSync(dirname(join(DIST, f)), {recursive: true})
  writeFileSync(join(DIST, f.replace(/\.ts$/, '.js')), `// Built from src/${f} by scripts/build.ts. Do not edit.\n${js}`)
  // types for `npm run typecheck`: the tests import dist/*.js, whose types are those of src/*.ts (not in the npm package)
  const up = '../'.repeat(f.split('/').length)
  writeFileSync(join(DIST, f.replace(/\.ts$/, '.d.ts')), `// Types of dist/${f.replace(/\.ts$/, '.js')} for the typecheck. Written by scripts/build.ts.\nexport * from '${up}src/${f}'\n`)
}
writeFileSync(join(DIST, 'kernel.gen.d.ts'), "// Types of dist/kernel.gen.js for the typecheck. Written by scripts/build.ts.\nexport * from '../src/kernel.gen.d.ts'\n")

// 2. the proven rule -> standalone step function, plus the codec between the wrapper's requests and the machine's numbers
const kernelSrc = readFileSync(join(SRC, 'kernel.ts'))
const {kernel} = await import(pathToFileURL(join(SRC, 'kernel.ts')).href)
const {compileJs} = await import('gdp-wired/machine')
const R = kernel('none')
if (R.machine.name !== 'stopbar_kernel_none') throw new Error(`unexpected machine ${R.machine.name}`)
const machineJs: string = compileJs(R.machine)

const OPS = ['EDIT_CODE', 'EDIT_TEST', 'RUN_BUILD', 'RUN_TESTS', 'READ_SECRET', 'SHELL', 'APPROVE_TESTS', 'APPROVE_SHELL', 'RESUME', 'COMMIT']
const P = {maxRetries: 2, cap: 9}
const sample = {op: 'EDIT_CODE', cost: 0, passed: false, fullSuite: false, suspicious: false, risky: false, treeChanged: false, approveRev: 0, extra: 0}
const inputs = R.machine.inputs.map((name: string) => {
  if (name === 'op') {
    const idx = OPS.map((op) => R.encodeInput({...sample, op}, P).op)
    if (idx.some((v: number, i: number) => v !== i)) throw new Error(`op encoding is not the expected order: ${idx}`)
    return {name, kind: 'oneOf', values: OPS}
  }
  if (typeof (sample as any)[name] === 'boolean') {
    if (R.encodeInput({...sample, [name]: true}, P)[name] !== 1) throw new Error(`${name} does not encode true as 1`)
    return {name, kind: 'bool'}
  }
  if (R.encodeInput({...sample, [name]: 7}, P)[name] !== 7) throw new Error(`${name} is not a plain natural`)
  return {name, kind: 'nat'}
})
const kinds = new Map(R.kindsOfState().map(([k, v]: [string, any]) => [k, v]))
const init = R.interpreter().init(R.encodeParams(P))
const state = Object.keys(init.scalars).map((name) => {
  const k: any = kinds.get(name)
  if (!k) return {name, kind: 'nat'}
  if (Array.isArray(k.values)) return {name, kind: 'oneOf', values: k.values}
  return {name, kind: 'bool'}
})
// the codec must reproduce gdp-wired's own decode
const dec = R.decode(init)
for (const f of state) {
  const v = init.scalars[f.name]
  const mine = f.kind === 'bool' ? v === 1 : f.kind === 'oneOf' ? f.values[v] : v
  if (mine !== dec[f.name]) throw new Error(`codec mismatch for ${f.name}: ${mine} vs ${dec[f.name]}`)
}

const gen = `// GENERATED by scripts/build.ts from src/kernel.ts with gdp-wired 0.60.0 compileJs. Do not edit.
// stopbar verify and the tests regenerate it and compare: KERNEL_SOURCE_SHA256 = sha256(src/kernel.ts),
// MACHINE_SHA256 = sha256(compileJs output below).
export const MACHINE_NAME = ${JSON.stringify(R.machine.name)}
export const KERNEL_SOURCE_SHA256 = ${JSON.stringify(sha(kernelSrc))}
export const MACHINE_SHA256 = ${JSON.stringify(sha(machineJs))}
export const CODEC = ${JSON.stringify({inputs, state})}
// ---- compileJs output (unchanged) ----
${machineJs}`
writeFileSync(join(DIST, 'kernel.gen.js'), gen)
writeFileSync(join(DIST, 'build-info.json'), JSON.stringify({version: JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version,
  kernelSourceSha256: sha(kernelSrc), machineSha256: sha(machineJs), files: files.length}, null, 1) + '\n')
console.log(`build ok: ${files.length} modules, kernel ${R.machine.name} sha256 ${sha(kernelSrc).slice(0, 16)}, machine ${sha(machineJs).slice(0, 16)} (${Date.now() - t0} ms)`)
